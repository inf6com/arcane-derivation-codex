#!/usr/bin/env python3
"""Train a font-only dense shape descriptor and emit contour/skeleton subsets.

The model is self-supervised: geometric correspondences are generated by known
small scale/translation views of each typeset glyph. It never consumes online
strokes, handwriting, class-confusion matrices, or outer-test samples.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from collections import defaultdict
from pathlib import Path

import numpy as np
import torch
from torch import nn
from torch.nn import functional as F
from torch.utils.data import DataLoader, TensorDataset, WeightedRandomSampler


class DenseShapeDescriptor(nn.Module):
    def __init__(self, width: int = 48, descriptor_dim: int = 24) -> None:
        super().__init__()
        self.features = nn.Sequential(
            nn.Conv2d(2, width, 3, padding=1, bias=False), nn.GroupNorm(8, width), nn.GELU(),
            nn.Conv2d(width, width, 3, padding=1, bias=False), nn.GroupNorm(8, width), nn.GELU(),
            nn.Conv2d(width, width, 3, padding=1, bias=False), nn.GroupNorm(8, width), nn.GELU(),
            nn.Conv2d(width, descriptor_dim, 1, bias=True),
        )

    def forward(self, shape: torch.Tensor) -> torch.Tensor:
        return F.normalize(self.features(shape), p=2, dim=1, eps=1e-6)


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def shape_channels(images: torch.Tensor) -> torch.Tensor:
    """Create a binary outline channel and medial skeleton channel on-device."""
    ink = (images >= (128.0 / 255.0)).to(images.dtype)
    # Erosion through complement dilation. Glyphs have a measured four-pixel inset.
    eroded = 1.0 - F.max_pool2d(1.0 - ink, 3, stride=1, padding=1)
    contour = (ink - eroded).clamp_(0, 1)
    current = ink
    skeleton = torch.zeros_like(ink)
    for _ in range(32):
        eroded = 1.0 - F.max_pool2d(1.0 - current, 3, stride=1, padding=1)
        opened = F.max_pool2d(eroded, 3, stride=1, padding=1)
        skeleton = torch.maximum(skeleton, (current - opened).clamp_(0, 1))
        current = eroded
        if not torch.any(current):
            break
    return torch.cat((contour, skeleton), dim=1)


def affine_views(x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    b = x.shape[0]
    device, dtype = x.device, x.dtype
    theta = torch.zeros((b, 2, 3), device=device, dtype=dtype)
    theta[:, 0, 0] = torch.empty(b, device=device, dtype=dtype).uniform_(0.90, 1.10)
    theta[:, 1, 1] = torch.empty(b, device=device, dtype=dtype).uniform_(0.90, 1.10)
    theta[:, 0, 2] = torch.empty(b, device=device, dtype=dtype).uniform_(-0.07, 0.07)
    theta[:, 1, 2] = torch.empty(b, device=device, dtype=dtype).uniform_(-0.07, 0.07)
    grid_a = F.affine_grid(theta, x.shape, align_corners=False)
    # Independent translations/scales, both sampled around the same glyph.
    theta_b = torch.zeros_like(theta)
    theta_b[:, 0, 0] = torch.empty(b, device=device, dtype=dtype).uniform_(0.90, 1.10)
    theta_b[:, 1, 1] = torch.empty(b, device=device, dtype=dtype).uniform_(0.90, 1.10)
    theta_b[:, 0, 2] = torch.empty(b, device=device, dtype=dtype).uniform_(-0.07, 0.07)
    theta_b[:, 1, 2] = torch.empty(b, device=device, dtype=dtype).uniform_(-0.07, 0.07)
    grid_b = F.affine_grid(theta_b, x.shape, align_corners=False)
    view_a = F.grid_sample(x, grid_a, mode="bilinear", padding_mode="zeros", align_corners=False)
    view_b = F.grid_sample(x, grid_b, mode="bilinear", padding_mode="zeros", align_corners=False)
    inv_a = torch.zeros_like(theta)
    inv_b = torch.zeros_like(theta)
    for src, dst in ((theta, inv_a), (theta_b, inv_b)):
        dst[:, 0, 0] = src[:, 0, 0].reciprocal(); dst[:, 1, 1] = src[:, 1, 1].reciprocal()
        dst[:, 0, 2] = -src[:, 0, 2] / src[:, 0, 0]
        dst[:, 1, 2] = -src[:, 1, 2] / src[:, 1, 1]
    align_a = F.affine_grid(inv_a, (b, 1, x.shape[-2], x.shape[-1]), align_corners=False)
    align_b = F.affine_grid(inv_b, (b, 1, x.shape[-2], x.shape[-1]), align_corners=False)
    return view_a, view_b, torch.stack((align_a, align_b), dim=0)


def select_points(mask: torch.Tensor, count: int) -> torch.Tensor:
    """Deterministically spaced ink samples per image, padded by explicit validity."""
    b, _, h, w = mask.shape
    flat = mask[:, 0].flatten(1) > 0.5
    indices = torch.zeros((b, count), device=mask.device, dtype=torch.long)
    valid = torch.zeros((b, count), device=mask.device, dtype=torch.bool)
    for i in range(b):
        found = torch.nonzero(flat[i], as_tuple=False).flatten()
        if found.numel() == 0:
            continue
        take = min(count, found.numel())
        positions = torch.linspace(0, found.numel() - 1, take, device=mask.device).round().long()
        indices[i, :take] = found[positions]
        valid[i, :take] = True
    return indices, valid


def contrastive_loss(a: torch.Tensor, b: torch.Tensor, valid: torch.Tensor) -> torch.Tensor:
    # Within-glyph negatives prevent a descriptor from collapsing to a constant.
    logits = torch.matmul(a, b.transpose(1, 2)) / 0.08
    logits = logits.masked_fill(~valid[:, None, :], -1e4)
    target = torch.arange(a.shape[1], device=a.device).expand(a.shape[0], -1)
    flat = F.cross_entropy(logits.reshape(-1, logits.shape[-1]), target.reshape(-1), reduction="none")
    weights = valid.reshape(-1).to(flat.dtype)
    return (flat * weights).sum() / weights.sum().clamp_min(1)


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser()
    p.add_argument('--manifest', type=Path, default=Path('runs/agent-control/cycle622-firebird-mac-font-glyphs.json'))
    p.add_argument('--images', type=Path, default=Path('runs/agent-control/cycle622-firebird-mac-font-glyphs.u8'))
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--epochs', type=int, default=3)
    p.add_argument('--batch-size', type=int, default=96)
    p.add_argument('--seed', type=int, default=20261104)
    return p.parse_args()


def main() -> None:
    args = parse_args()
    if not torch.backends.mps.is_available():
        raise RuntimeError('MPS is unavailable; refusing CPU training.')
    if args.output.exists():
        raise FileExistsError(args.output)
    manifest_bytes = args.manifest.read_bytes()
    manifest = json.loads(manifest_bytes)
    if manifest.get('schema') != 'firebird-mac-font-glyph-raster-v1' or manifest['renderedImageCount'] != 68689:
        raise ValueError('Unexpected authoritative Mac font glyph corpus.')
    if args.images.stat().st_size != manifest['renderedImageCount'] * manifest['height'] * manifest['width']:
        raise ValueError('Raster byte size disagrees with its manifest.')
    if args.epochs < 1 or args.batch_size < 8:
        raise ValueError('Invalid training configuration.')

    torch.manual_seed(args.seed)
    np.random.seed(args.seed)
    device = torch.device('mps')
    rows = manifest['rows']
    font_hashes = sorted({r['fontFileSHA256'] for r in rows})
    ranked = sorted(font_hashes, key=lambda h: hashlib.sha256(f'{args.seed}:{h}'.encode()).digest())
    heldout = set(ranked[:max(1, round(len(ranked) * 0.20))])
    fit_indices = [i for i, r in enumerate(rows) if r['fontFileSHA256'] not in heldout]
    valid_indices = [i for i, r in enumerate(rows) if r['fontFileSHA256'] in heldout]
    if set(rows[i]['fontFileSHA256'] for i in fit_indices) & set(heldout):
        raise AssertionError('Font-file split leakage.')
    args.output.mkdir(parents=True)
    raster = np.memmap(args.images, mode='r', dtype=np.uint8,
                       shape=(manifest['renderedImageCount'], 64, 64))
    shape_path = args.output / 'contour-skeleton-corpus.u8'
    shape_memmap = np.memmap(shape_path, mode='w+', dtype=np.uint8,
                             shape=(manifest['renderedImageCount'], 2, 64, 64))
    for start in range(0, manifest['renderedImageCount'], 384):
        end = min(start + 384, manifest['renderedImageCount'])
        images = torch.from_numpy(np.array(raster[start:end], copy=True)).to(device=device, dtype=torch.float32).div_(255.0).unsqueeze(1)
        maps = shape_channels(images).mul_(255).round().to(torch.uint8).cpu().numpy()
        shape_memmap[start:end] = maps
        if (start // 384) % 20 == 0:
            print(json.dumps({'stage':'shape-corpus','processed':end,'total':manifest['renderedImageCount']}), flush=True)
    shape_memmap.flush()
    fit = torch.from_numpy(np.array(shape_memmap[fit_indices], copy=True))
    labels = torch.tensor([rows[i]['vocabularyIndex'] for i in fit_indices], dtype=torch.long)
    counts = torch.bincount(labels)
    sample_weights = counts[labels].clamp_min(1).float().reciprocal()
    sampler = WeightedRandomSampler(sample_weights, len(labels), replacement=True,
                                    generator=torch.Generator().manual_seed(args.seed))
    loader = DataLoader(TensorDataset(fit), batch_size=args.batch_size, sampler=sampler,
                        num_workers=0, drop_last=True)
    model = DenseShapeDescriptor().to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=2e-4, weight_decay=1e-4)
    history = []
    for epoch in range(1, args.epochs + 1):
        model.train(); total = 0.0; seen = 0
        for batch_index, (batch,) in enumerate(loader, start=1):
            x = batch.to(device=device, dtype=torch.float32).div_(255.0)
            a_img, b_img, grids = affine_views(x)
            da = model(a_img); db = model(b_img)
            # Align view descriptors back into the source glyph's normalized frame.
            da = F.grid_sample(da, grids[0], mode='bilinear', padding_mode='zeros', align_corners=False)
            db = F.grid_sample(db, grids[1], mode='bilinear', padding_mode='zeros', align_corners=False)
            da = F.normalize(da, p=2, dim=1, eps=1e-6)
            db = F.normalize(db, p=2, dim=1, eps=1e-6)
            source_skeleton = x[:, 1:2]
            point_ids, valid_points = select_points(source_skeleton, 32)
            bsz, dim, h, w = da.shape
            da_flat = da.permute(0, 2, 3, 1).reshape(bsz, h*w, dim)
            db_flat = db.permute(0, 2, 3, 1).reshape(bsz, h*w, dim)
            aa = torch.gather(da_flat, 1, point_ids[..., None].expand(-1, -1, dim))
            bb = torch.gather(db_flat, 1, point_ids[..., None].expand(-1, -1, dim))
            loss = contrastive_loss(aa, bb, valid_points)
            optimizer.zero_grad(set_to_none=True); loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), 1.0); optimizer.step()
            total += float(loss.detach()); seen += 1
            if batch_index % 100 == 0:
                print(json.dumps({'stage':'training','epoch':epoch,'batch':batch_index,
                                  'batchCount':len(loader),'loss':total/seen}), flush=True)
        row = {'epoch': epoch, 'trainingLoss': total / max(seen, 1), 'batches': seen,
               'fitFontFiles': len(set(rows[i]['fontFileSHA256'] for i in fit_indices)),
               'heldoutFontFiles': len(heldout), 'fitRasterCount': len(fit_indices),
               'heldoutRasterCount': len(valid_indices)}
        history.append(row); print(json.dumps(row), flush=True)

    model.eval()
    positive_scores, negative_scores, retrieval_hits, retrieval_total = [], [], 0, 0
    with torch.inference_mode():
        for start in range(0, min(len(valid_indices), 2048), 64):
            end = min(start + 64, min(len(valid_indices), 2048))
            ids = valid_indices[start:end]
            x = torch.from_numpy(np.array(shape_memmap[ids], copy=True)).to(device=device, dtype=torch.float32).div_(255.0)
            a_img, b_img, grids = affine_views(x)
            da = model(a_img); db = model(b_img)
            da = F.grid_sample(da, grids[0], mode='bilinear', padding_mode='zeros', align_corners=False)
            db = F.grid_sample(db, grids[1], mode='bilinear', padding_mode='zeros', align_corners=False)
            da = F.normalize(da, p=2, dim=1, eps=1e-6)
            db = F.normalize(db, p=2, dim=1, eps=1e-6)
            point_ids, point_valid = select_points(x[:, 1:2], 32)
            n, dim, h, w = da.shape
            af = da.permute(0,2,3,1).reshape(n,h*w,dim)
            bf = db.permute(0,2,3,1).reshape(n,h*w,dim)
            aa = F.normalize(torch.gather(af,1,point_ids[...,None].expand(-1,-1,dim)),dim=-1)
            bb = F.normalize(torch.gather(bf,1,point_ids[...,None].expand(-1,-1,dim)),dim=-1)
            sims = torch.bmm(aa,bb.transpose(1,2))
            diagonal = sims.diagonal(dim1=1,dim2=2)
            positive_scores.extend(diagonal[point_valid].cpu().tolist())
            off = ~torch.eye(sims.shape[1],device=device,dtype=torch.bool).unsqueeze(0)
            off = off & point_valid[:,:,None] & point_valid[:,None,:]
            negative_scores.extend(sims[off].cpu().tolist())
            valid_rows = point_valid.any(dim=1)
            masked = sims.masked_fill(~point_valid[:,None,:], -2)
            hits = masked.argmax(dim=-1).eq(torch.arange(sims.shape[1],device=device)[None,:]) & point_valid
            retrieval_hits += int(hits.sum().item()); retrieval_total += int(point_valid.sum().item())
    validation_metric = {
        'fontHeldoutGlyphImagesSampled': min(len(valid_indices), 2048),
        'correspondenceRecallAt1': retrieval_hits / max(retrieval_total,1),
        'meanPositiveCosine': float(np.mean(positive_scores)),
        'meanWithinGlyphNegativeCosine': float(np.mean(negative_scores)),
        'positiveCosineP05': float(np.quantile(positive_scores,0.05)),
        'negativeCosineP99': float(np.quantile(negative_scores,0.99)),
    }

    checkpoint = args.output / 'firebird-part-descriptor.pt'
    torch.save({'state_dict': {k: v.detach().cpu() for k,v in model.state_dict().items()},
                'architecture': {'type':'DenseShapeDescriptor','inputChannels':['contour','skeleton'],
                                 'width':48,'descriptorDimension':24},
                'trainingObjective':'within-glyph dense descriptor correspondence under known small scale/translation views',
                'seed':args.seed,'epochs':args.epochs}, checkpoint)
    report = {'schema':'firebird-typeset-part-descriptor-training-v1','corpusManifestSHA256':hashlib.sha256(manifest_bytes).hexdigest(),
              'corpusRasterSHA256':sha256(args.images),'fontSplitSHA256':hashlib.sha256(json.dumps(sorted(heldout)).encode()).hexdigest(),
              'trainingFontFiles':sorted(set(rows[i]['fontFileSHA256'] for i in fit_indices)),
              'heldoutFontFiles':sorted(heldout),'epochs':history,'checkpoint':str(checkpoint),
              'heldoutFontCorrespondenceValidation':validation_metric,
              'trainingDevice':str(device),'outerTestOpened':False,
              'scope':'Typeset font images only. Contours and skeletons are derived from filled glyph rasters; no stroke data or confusion labels are used.',
              'limitation':'This checkpoint learns local shape descriptors, not semantic part annotations. Shared-subset thresholding must be calibrated on heldout-font geometric matches before publication.'}
    (args.output/'training-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')


if __name__ == '__main__':
    main()
