// MARK: - Inf6CircuitBoardView

struct Inf6CircuitBoardView: View {

    var focusRawID: String? = nil
    var onSelectNode: ((String) -> Void)?
    var onSelectPaper: ((String) -> Void)?
    @AppStorage("gen_lang") private var genLangRaw: String = "ja"

    var body: some View {
        _CircuitBoardWebView(
            languageCode: _normalizedLanguageCode(genLangRaw),
            focusRawID: focusRawID,
            onSelectNode: onSelectNode,
            onSelectPaper: onSelectPaper
        )
            .ignoresSafeArea()
    }

    private func _normalizedLanguageCode(_ raw: String) -> String {
        let code = raw.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        switch code {
        case "en":
            return "en"
        case "auto":
            let preferred = (Locale.preferredLanguages.first ?? Locale.current.identifier).lowercased()
            return preferred.hasPrefix("ja") ? "ja" : "en"
        default:
            return "ja"
        }
    }

    static func invalidateRenderedCache() {
        _CircuitBoardWebView.Coordinator.invalidateCache()
    }
}

// MARK: - WKWebView wrapper

private struct _CircuitBoardWebView: UIViewRepresentable {

    var languageCode: String
    var focusRawID: String?
    var onSelectNode: ((String) -> Void)?
    var onSelectPaper: ((String) -> Void)?

    func makeCoordinator() -> Coordinator {
        Coordinator()
    }

    func makeUIView(context: Context) -> WKWebView {
        let coord = context.coordinator
        let config = WKWebViewConfiguration()
        config.userContentController.add(coord, name: "nodeTap")
        config.userContentController.add(coord, name: "paperTap")

        let webView = WKWebView(frame: .zero, configuration: config)
        webView.isOpaque = false
        webView.backgroundColor = .clear
        webView.scrollView.isScrollEnabled = true
        webView.scrollView.bounces = true

        coord.webView = webView
        coord.onSelectNode = onSelectNode
        coord.onSelectPaper = onSelectPaper
        coord.apply(languageCode: languageCode, focusRawID: focusRawID)
        return webView
    }

    func updateUIView(_ webView: WKWebView, context: Context) {
        let coord = context.coordinator
        coord.onSelectNode = onSelectNode
        coord.onSelectPaper = onSelectPaper
        coord.apply(languageCode: languageCode, focusRawID: focusRawID)
    }

    // MARK: - Coordinator

    final class Coordinator: NSObject, WKScriptMessageHandler, WKNavigationDelegate {
        weak var webView: WKWebView? {
            didSet { webView?.navigationDelegate = self }
        }
        var onSelectNode: ((String) -> Void)?
        var onSelectPaper: ((String) -> Void)?
        private var requestedLanguageCode: String = "ja"
        private var requestedFocusRawID: String?
        private var injectedLanguageCode: String?
        private var injectedFocusRawID: String?
        private var pageLoaded = false

        override init() {
            super.init()
        }

        // SSR mode: HTML is generated by Swift and loaded from a cache file.
        func webView(_ webView: WKWebView, didFinish navigation: WKNavigation!) {
            pageLoaded = true
            print(String(format: "[CircuitBoard] WebView didFinish at %.3f", CACurrentMediaTime()))
        }

        func apply(languageCode: String, focusRawID: String?) {
            requestedLanguageCode = languageCode
            requestedFocusRawID = focusRawID
            let focusKey = focusRawID?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
            // Skip if already showing the same language with current data fingerprint.
            if injectedLanguageCode == languageCode,
               (injectedFocusRawID ?? "") == focusKey,
               let cached = Self._cachedPayload,
               cached.fingerprint == _injectionFingerprint() + "|lang=\(languageCode)|focus=\(focusKey)" {
                return
            }
            _renderAndLoad(languageCode: languageCode, focusRawID: focusRawID)
        }

        func userContentController(_ uc: WKUserContentController,
                                     didReceive message: WKScriptMessage) {
            guard let id = message.body as? String else { return }
            DispatchQueue.main.async { [weak self] in
                switch message.name {
                case "nodeTap":
                    self?.onSelectNode?(id)
                case "paperTap":
                    self?.onSelectPaper?(id)
                default:
                    break
                }
            }
        }

        // ==== SSR: pre-rendered static HTML cached to disk ====

        private static func _ssrHTMLFileURL() -> URL? {
            try? Inf6UserSettingRootPaths.cacheFileURL("circuit_board_ssr", ext: "html")
        }

        // In-process record of "what fingerprint we just loaded".
        private struct _CachedPayload {
            let fingerprint: String
        }
        private static var _cachedPayload: _CachedPayload?
        private static let _cacheLock = NSLock()

        /// Cheap fingerprint of all inputs that determine the output HTML.
        private func _injectionFingerprint() -> String {
            let manifests = Inf6LearningFamilyManifestStore.loadAll()
            var parts: [String] = []
            // Renderer version: changing this invalidates SSR cache so visual
            // changes in the renderer immediately take effect on next launch.
            parts.append("rv:\(Inf6CircuitBoardHTMLRenderer.rendererVersion)")
            for m in manifests {
                parts.append(m.sourceFamily)
                let syllabusVersionID = _resolvedKnowledgeStructureVersionID(for: m)
                parts.append(syllabusVersionID)
                if let url = try? Inf6KnowledgeDomainStructureStore.fileURL(
                    manifest: m, syllabusVersionID: syllabusVersionID
                ) {
                    let attrs = try? FileManager.default.attributesOfItem(atPath: url.path)
                    let mtime = (attrs?[.modificationDate] as? Date)?.timeIntervalSince1970 ?? 0
                    parts.append(String(mtime))
                }
            }
            if let outlineURL = try? Inf6Storage.syllabusOutlineCacheURL() {
                let attrs = try? FileManager.default.attributesOfItem(atPath: outlineURL.path)
                let mtime = (attrs?[.modificationDate] as? Date)?.timeIntervalSince1970 ?? 0
                parts.append("outline:\(mtime)")
            }
            parts.append("ps:\(Inf6CorePaperStore.shared.papers.count)")
            return parts.joined(separator: "|")
        }

        /// Generate the HTML (if needed), write to cache file, and ask the
        /// WebView to load it.
        private func _renderAndLoad(languageCode: String, focusRawID: String?) {
            let lang = languageCode == "en" ? "en" : "ja"
            let focusKey = focusRawID?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
            let fp = _injectionFingerprint() + "|lang=\(lang)|focus=\(focusKey)"

            guard let fileURL = Self._ssrHTMLFileURL() else {
                _renderCircuitBoardError("cache file URL unavailable")
                return
            }

            let fm = FileManager.default
            let alreadyMatches: Bool = {
                Self._cacheLock.lock()
                defer { Self._cacheLock.unlock() }
                return Self._cachedPayload?.fingerprint == fp && fm.fileExists(atPath: fileURL.path)
            }()

            let startedAt = CACurrentMediaTime()
            if alreadyMatches {
                print(String(format: "[CircuitBoard] cache hit, reload only (fp=%@)", String(fp.prefix(40))))
            } else {
                let tLoadStart = CACurrentMediaTime()
                let html: String
                let tLoadEnd: CFTimeInterval
                if focusKey.isEmpty {
                    let manifests = Inf6LearningFamilyManifestStore.loadAll()
                    tLoadEnd = CACurrentMediaTime()
                    html = Inf6CircuitBoardHTMLRenderer.renderHomeHTML(manifests: manifests, lang: lang)
                } else {
                    let domains: [[String: Any]]
                    do {
                        domains = try _loadDomainStructures()
                    } catch {
                        _renderCircuitBoardError(error.localizedDescription)
                        return
                    }
                    tLoadEnd = CACurrentMediaTime()
                    html = Inf6CircuitBoardHTMLRenderer.renderHTML(domains: domains, lang: lang, focusRawID: focusRawID)
                }
                let tHTMLEnd = CACurrentMediaTime()
                do {
                    try html.write(to: fileURL, atomically: true, encoding: .utf8)
                } catch {
                    _renderCircuitBoardError("ssr write failed: \(error.localizedDescription)")
                    return
                }
                let tWriteEnd = CACurrentMediaTime()
                Self._cacheLock.lock()
                Self._cachedPayload = _CachedPayload(fingerprint: fp)
                Self._cacheLock.unlock()
                print(String(format: "[CircuitBoard] SSR generated: load=%.1fms render=%.1fms write=%.1fms total=%.1fms html=%d bytes lang=%@",
                             (tLoadEnd - tLoadStart) * 1000,
                             (tHTMLEnd - tLoadEnd) * 1000,
                             (tWriteEnd - tHTMLEnd) * 1000,
                             (tWriteEnd - tLoadStart) * 1000,
                             html.utf8.count,
                             lang))
            }

            webView?.loadFileURL(fileURL, allowingReadAccessTo: fileURL.deletingLastPathComponent())
            let loadElapsed = (CACurrentMediaTime() - startedAt) * 1000
            print(String(format: "[CircuitBoard] loadFileURL dispatched (elapsed=%.1fms)", loadElapsed))
            injectedLanguageCode = languageCode
            injectedFocusRawID = focusKey
        }

        static func invalidateCache() {
            if let url = _ssrHTMLFileURL() {
                try? FileManager.default.removeItem(at: url)
            }
            _cacheLock.lock()
            _cachedPayload = nil
            _cacheLock.unlock()
            Inf6KnowledgeDomainStructureStore.invalidateCache()
        }

        private func _renderCircuitBoardError(_ message: String) {
            let escaped = message
                .replacingOccurrences(of: "<", with: "&lt;")
                .replacingOccurrences(of: ">", with: "&gt;")
            let html = """
            <!DOCTYPE html><html><head><meta charset="utf-8"/></head><body>
            <pre style="color:#b42318;font-family:-apple-system;font-size:14px;padding:16px;white-space:pre-wrap">\(escaped)</pre>
            </body></html>
            """
            webView?.loadHTMLString(html, baseURL: nil)
        }

        /// Inf6KnowledgeDomainStructureStore 経由で型付きモデルをロードし、JS用辞書に変換する。
        private func _loadDomainStructures() throws -> [[String: Any]] {
            let tStart = CACurrentMediaTime()
            let manifests = Inf6LearningFamilyManifestStore.loadAll()
            let tManifests = CACurrentMediaTime()
            let outlineCache = _loadOutlineCache()
            let tOutlineCache = CACurrentMediaTime()

            // Hoist heavy per-paper file I/O OUT of the per-domain loop.
            // Previously these were computed inside _structureToDict for every
            // domain (3× duplication of the same 84 file-scans).
            let corePaperStore = Inf6CorePaperStore.shared
            let tBulk0 = CACurrentMediaTime()
            let achievementOverrides = (try? Inf6AchievementOverrideStore.load()) ?? [:]
            let tBulk1 = CACurrentMediaTime()
            // Compute heavy bulk states FIRST so the achievement lookup can reuse them.
            let learningArtifactStates = corePaperStore.learningArtifactStateByPaperID()
            let tBulk2 = CACurrentMediaTime()
            let assetsPipelineStates = corePaperStore.assetsPipelineStateByPaperID()
            let tBulk3 = CACurrentMediaTime()
            // Fast achievement aggregation that reuses the bulk caches (no extra I/O).
            let progressAchievements = corePaperStore.achievementByPaperID(
                assetsPipelineStates: assetsPipelineStates,
                learningArtifactStates: learningArtifactStates
            )
            let tBulk4 = CACurrentMediaTime()
            let bulk = _PerLoadCaches(
                achievementOverrides: achievementOverrides,
                progressAchievements: progressAchievements,
                learningArtifactStates: learningArtifactStates,
                assetsPipelineStates: assetsPipelineStates,
                corePapers: corePaperStore.papers
            )
            print(String(format: "[CircuitBoard][load] manifests=%.1fms outlineCache=%.1fms BULK overrides=%.1f learning=%.1f assets=%.1f progress=%.1f (manifests=%d, papers=%d)",
                         (tManifests - tStart) * 1000,
                         (tOutlineCache - tManifests) * 1000,
                         (tBulk1 - tBulk0) * 1000,
                         (tBulk2 - tBulk1) * 1000,
                         (tBulk3 - tBulk2) * 1000,
                         (tBulk4 - tBulk3) * 1000,
                         manifests.count,
                         corePaperStore.papers.count))
            var result: [[String: Any]] = []

            for manifest in manifests {
                let tM0 = CACurrentMediaTime()
                let paperStore: Inf6CorePaperStore? = Inf6CorePaperStore.shared
                let outlineItems = try _findOutlineItems(for: manifest, cache: outlineCache)
                let syllabusVersionID = _resolvedKnowledgeStructureVersionID(for: manifest)
                let tM1 = CACurrentMediaTime()

                let structure = try Inf6KnowledgeDomainStructureStore.loadOrSeed(
                    manifest: manifest,
                    syllabusVersionID: syllabusVersionID,
                    domainTitleJa: manifest.displayNameJa,
                    outlineItems: outlineItems,
                    paperStore: paperStore
                )
                let tM2 = CACurrentMediaTime()

                let sourceSnapshot = _loadOfficialSourceSnapshotForManifest(manifest)
                let tM3 = CACurrentMediaTime()
                let explicitYears = _explicitYears(manifest: manifest, sourceSnapshot: sourceSnapshot)
                let tM4 = CACurrentMediaTime()

                let domainDict = try _structureToDict(structure, manifest: manifest, explicitYears: explicitYears, sourceSnapshot: sourceSnapshot, bulk: bulk)
                let tM5 = CACurrentMediaTime()
                let nodeCount = structure.nodes.count
                let paperCount = structure.papers.count
                print(String(format: "[CircuitBoard][load] %@: prep=%.1f loadOrSeed=%.1f snapshot=%.1f years=%.1f dict=%.1f (total=%.1fms) nodes=%d papers=%d",
                             manifest.sourceFamily,
                             (tM1 - tM0) * 1000,
                             (tM2 - tM1) * 1000,
                             (tM3 - tM2) * 1000,
                             (tM4 - tM3) * 1000,
                             (tM5 - tM4) * 1000,
                             (tM5 - tM0) * 1000,
                             nodeCount, paperCount))
                result.append(domainDict)
            }

            print(String(format: "[CircuitBoard][load] TOTAL=%.1fms", (CACurrentMediaTime() - tStart) * 1000))
            return result
        }

        /// Caches that are expensive to compute (touch many iCloud files) but
        /// stable across the manifests processed in a single _loadDomainStructures call.
        struct _PerLoadCaches {
            let achievementOverrides: [String: Inf6KnowledgeAchievementState]
            let progressAchievements: [String: Inf6KnowledgeAchievementState]
            let learningArtifactStates: [String: Inf6CorePaperLearningArtifactState]
            let assetsPipelineStates: [String: Inf6AssetsPipelineRunState]
            let corePapers: [Inf6CorePaper]
        }

        private func _structureToDict(
            _ structure: Inf6KnowledgeDomainStructure,
            manifest: Inf6LearningFamilyManifest,
            explicitYears: [Int],
            sourceSnapshot: [String: Any]?,
            bulk: _PerLoadCaches
        ) throws -> [String: Any] {
            let achievementOverrides = bulk.achievementOverrides
            let progressAchievements = bulk.progressAchievements
            let learningArtifactStates = bulk.learningArtifactStates
            let assetsPipelineStates = bulk.assetsPipelineStates
            let corePapersByID = Dictionary(
                uniqueKeysWithValues: bulk.corePapers.map { ($0.id, $0) }
            )
            let paperAchievementByID: [String: Inf6KnowledgeAchievementState] = structure.papers.reduce(into: [:]) { result, paper in
                let catalogAchievement: Inf6KnowledgeAchievementState = corePapersByID[paper.paperID] == nil ? paper.achievement : .notStarted
                result[paper.paperID] = achievementOverrides[paper.paperID] ?? progressAchievements[paper.paperID] ?? catalogAchievement
            }
            let paperArtifactSummaries: [String: [String: Bool]] = structure.papers.reduce(into: [:]) { result, paper in
                let artifactState = learningArtifactStates[paper.paperID] ?? Inf6CorePaperLearningArtifactState()
                result[paper.paperID] = [
                    "assets": assetsPipelineStates[paper.paperID] == .finished,
                    "overview": artifactState.hasOverview,
                    "formula": artifactState.hasFormulaCard || artifactState.hasFormulaExplanation,
                    "quiz": artifactState.hasQuiz,
                    "added_explanation": artifactState.hasAddedExplanation,
                ]
            }

            let nodes: [[String: Any]] = try structure.nodes
                .filter { $0.kind != .paper }
                .map { node in
                let titlePair = try _bilingualTitlePair(
                    ja: node.titleJa,
                    en: node.titleEn,
                    recordID: node.nodeID,
                    recordKind: "node"
                )
                let nodeAchievement = _resolvedNodeAchievement(node, paperAchievements: paperAchievementByID)
                var dict: [String: Any] = [
                    "node_id": node.nodeID,
                    "kind": node.kind.rawValue,
                    "depth": node.depth,
                    "title_ja": titlePair.ja,
                    "title_en": titlePair.en,
                    "summary_ja": node.summaryJa,
                    "summary_en": node.summaryEn,
                    "paper_count": node.paperCount,
                    "achievement": nodeAchievement.rawValue,
                    "achievement_sources": _achievementSourceSummary(
                        paperIDs: node.linkedPaperIDs,
                        paperArtifacts: paperArtifactSummaries
                    ),
                    "importance": node.importance,
                    "next_action": node.nextAction.rawValue,
                    "linked_paper_ids": node.linkedPaperIDs,
                ]
                if let parentID = node.parentNodeID {
                    dict["parent_node_id"] = parentID
                }
                return dict
            }

            let papers: [[String: Any]] = try structure.papers.map { paper in
                let corePaper = corePapersByID[paper.paperID]
                let titlePair = try _paperTitlePair(
                    raw: paper.paperTitle,
                    en: corePaper?.titleEn,
                    recordID: paper.paperID
                )
                let catalogAchievement: Inf6KnowledgeAchievementState = corePaper == nil ? paper.achievement : .notStarted
                let liveAchievement = achievementOverrides[paper.paperID] ?? progressAchievements[paper.paperID] ?? catalogAchievement
                var dict: [String: Any] = [
                    "paper_id": paper.paperID,
                    "paper_title": titlePair.en,
                    "paper_title_ja": titlePair.ja,
                    "paper_title_en": titlePair.en,
                    "provider_id": paper.providerID,
                    "syllabus_node_ids": paper.syllabusNodeIDs,
                    "achievement": liveAchievement.rawValue,
                    "knowledge_count": paper.knowledgeCount,
                ]
                if let year = corePapersByID[paper.paperID]?.year {
                    dict["source_year"] = year
                }
                dict["assets_pipeline_state"] = (assetsPipelineStates[paper.paperID] ?? .none).rawValue
                let artifactState = learningArtifactStates[paper.paperID] ?? Inf6CorePaperLearningArtifactState()
                dict["overview_state"] = artifactState.overviewState
                dict["formula_state"] = artifactState.formulaState
                dict["quiz_state"] = artifactState.quizState
                dict["added_explanation_state"] = artifactState.addedExplanationState
                return dict
            }

            let out: [String: Any] = [
                "domain_id": structure.domainID,
                "syllabus_version_id": structure.syllabusVersionID,
                "nodes": nodes,
                "papers": papers,
                "source_family": manifest.sourceFamily,
                "source_years": explicitYears,
                "source_year": explicitYears.max() ?? 0,
            ]

            // classification enrichment
            let enriched = _enrichedDomainJSON(out, manifest: manifest, explicitYears: explicitYears)
            try _validateBilingualHTMLInput(enriched, domainID: structure.domainID)
            return enriched
        }

        private func _resolvedNodeAchievement(
            _ node: Inf6KnowledgeNode,
            paperAchievements: [String: Inf6KnowledgeAchievementState]
        ) -> Inf6KnowledgeAchievementState {
            let states = node.linkedPaperIDs.compactMap { paperAchievements[$0] }
            guard !states.isEmpty else { return node.achievement }
            return _aggregateAchievement(states)
        }

        private func _aggregateAchievement(_ states: [Inf6KnowledgeAchievementState]) -> Inf6KnowledgeAchievementState {
            guard !states.isEmpty else { return .notStarted }
            let avg = states.map(_achievementFraction).reduce(0, +) / Double(states.count)
            if avg >= 0.95 { return .measured }
            if avg >= 0.74 { return .questioned }
            if avg >= 0.58 { return .explained }
            if avg >= 0.42 { return .annotating }
            if avg >= 0.24 { return .reading }
            if avg > 0 { return .collecting }
            return .notStarted
        }

        private func _achievementFraction(_ state: Inf6KnowledgeAchievementState) -> Double {
            switch state {
            case .notStarted: return 0
            case .collecting: return 0.16
            case .reading: return 0.34
            case .annotating: return 0.50
            case .explained: return 0.66
            case .questioned: return 0.82
            case .measured: return 1.0
            }
        }

        private func _achievementSourceSummary(
            paperIDs: [String],
            paperArtifacts: [String: [String: Bool]]
        ) -> [String: Any] {
            var counts: [String: Int] = [
                "assets": 0,
                "overview": 0,
                "formula": 0,
                "quiz": 0,
                "added_explanation": 0,
            ]
            var total = 0
            let sourceKeys = ["assets", "overview", "formula", "quiz", "added_explanation"]
            for paperID in paperIDs {
                guard let artifacts = paperArtifacts[paperID] else { continue }
                total += 1
                for key in sourceKeys {
                    if artifacts[key] == true {
                        counts[key, default: 0] += 1
                    }
                }
            }
            var out: [String: Any] = counts
            out["paper_total"] = total
            return out
        }

        private func _bilingualTitlePair(
            ja: String,
            en: String,
            recordID: String,
            recordKind: String
        ) throws -> (ja: String, en: String) {
            let trimmedJa = ja.trimmingCharacters(in: .whitespacesAndNewlines)
            let trimmedEn = en.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmedJa.isEmpty,
               !trimmedEn.isEmpty,
               !_containsJapanese(trimmedEn),
               (_containsJapanese(trimmedJa) || _isAcceptedLanguageNeutralTitle(trimmedJa)) {
                return (trimmedJa, trimmedEn)
            }
            throw NSError(
                domain: "Inf6CircuitBoard.BilingualInput",
                code: 1,
                userInfo: [NSLocalizedDescriptionKey: "HTML bilingual input missing: \(recordKind) \(recordID) title_ja=\(trimmedJa) title_en=\(trimmedEn)"]
            )
        }

        private func _paperTitlePair(raw: String, en: String?, recordID: String) throws -> (ja: String, en: String) {
            let title = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            let trimmedEn = (en ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmedEn.isEmpty && !_containsJapanese(trimmedEn) {
                return (title, trimmedEn)
            }
            if !title.isEmpty && !_containsJapanese(title) {
                return (title, title)
            }
            throw NSError(
                domain: "Inf6CircuitBoard.BilingualInput",
                code: 4,
                userInfo: [NSLocalizedDescriptionKey: "HTML bilingual input missing: paper \(recordID) paper_title_ja=\(title) paper_title_en="]
            )
        }

        private func _validateBilingualHTMLInput(_ domain: [String: Any], domainID: String) throws {
            let nodes = (domain["nodes"] as? [[String: Any]]) ?? []
            for node in nodes {
                let id = (node["node_id"] as? String) ?? "(unknown)"
                let en = (node["title_en"] as? String) ?? ""
                if en.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty || _containsJapanese(en) {
                    throw NSError(
                        domain: "Inf6CircuitBoard.BilingualInput",
                        code: 2,
                        userInfo: [NSLocalizedDescriptionKey: "HTML bilingual input invalid: domain \(domainID) node \(id) title_en=\(en)"]
                    )
                }
            }
            let papers = (domain["papers"] as? [[String: Any]]) ?? []
            for paper in papers {
                let id = (paper["paper_id"] as? String) ?? "(unknown)"
                let en = (paper["paper_title_en"] as? String) ?? (paper["paper_title"] as? String) ?? ""
                if en.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty || _containsJapanese(en) {
                    throw NSError(
                        domain: "Inf6CircuitBoard.BilingualInput",
                        code: 3,
                        userInfo: [NSLocalizedDescriptionKey: "HTML bilingual input invalid: domain \(domainID) paper \(id) paper_title_en=\(en)"]
                    )
                }
            }
        }

        private func _containsJapanese(_ text: String) -> Bool {
            text.range(of: #"[ぁ-んァ-ン一-龥]"#, options: .regularExpression) != nil
        }

        private func _isAcceptedLanguageNeutralTitle(_ text: String) -> Bool {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return false }
            return trimmed.count <= 32
                && trimmed.range(of: #"^[A-Za-z0-9 ._+\-/#()]+$"#, options: .regularExpression) != nil
        }

        private func _loadOutlineCache() -> [String: [Inf6SyllabusOutlineItem]] {
            guard let url = try? Inf6Storage.syllabusOutlineCacheURL() else { return [:] }
            return Inf6DiskJSON.load([String: [Inf6SyllabusOutlineItem]].self, from: url) ?? [:]
        }

        private func _findOutlineItems(
            for manifest: Inf6LearningFamilyManifest,
            cache: [String: [Inf6SyllabusOutlineItem]]
        ) throws -> [Inf6SyllabusOutlineItem] {
            if manifest.sourceFamily == "jdla_gkentei" {
                return try _loadStructuredGkenteiSyllabusItems(manifest: manifest)
            }
            if manifest.usesMicrosoftLearnProvider {
                let preferred = _findMicrosoftLearnOutlineItems(for: manifest, cache: cache)
                if !preferred.isEmpty {
                    return preferred
                }
                throw NSError(
                    domain: "Inf6CircuitBoardView",
                    code: 30,
                    userInfo: [NSLocalizedDescriptionKey: "Microsoft Learn bilingual outline is missing: \(manifest.sourceFamily). Fetch both en-us and ja-jp sources before rendering."]
                )
            }
            let familyID = manifest.familyID
            let patterns: [String] = {
                switch familyID {
                case "g-kentei":
                    return ["gkentei_outline", "g-syllabus", "g%e6%a4%9c%e5%ae%9a"]
                case "e-shikaku":
                    return ["eshikaku_outline", "e-syllabus", "e%e8%b3%87%e6%a0%bc"]
                case "ai-102":
                    return ["ai-102", "azure"]
                case "ai-103":
                    return ["ai-103", "azure"]
                default:
                    return []
                }
            }()
            guard !patterns.isEmpty else { return [] }
            var candidates: [[Inf6SyllabusOutlineItem]] = []
            for (key, items) in cache {
                let lowKey = key.lowercased()
                if patterns.contains(where: { lowKey.contains($0) }) {
                    candidates.append(items)
                }
            }
            return candidates.max(by: { $0.count < $1.count }) ?? []
        }

