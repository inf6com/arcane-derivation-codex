        private func _enrichedDomainJSON(
            _ domain: [String: Any],
            manifest: Inf6LearningFamilyManifest?,
            explicitYears: [Int]
        ) -> [String: Any] {
            var out = domain
            let domainYears = Set(explicitYears)
            let nodes = (domain["nodes"] as? [[String: Any]]) ?? []
            let papers = (domain["papers"] as? [[String: Any]]) ?? []
            let rootByNodeID = _rootClassificationByNodeID(nodes)

            out["source_years"] = Array(domainYears).sorted()
            out["source_year"] = domainYears.max()

            out["nodes"] = nodes.map { node in
                var item = node
                guard let nodeID = item["node_id"] as? String else { return item }
                if item["kind"] as? String == "domain" || item["kind"] as? String == "syllabus_version" {
                    return item
                }

                if let classID = _scienceClassificationID(_classificationText(from: item)) ?? rootByNodeID[nodeID] ?? _classificationID(from: item) {
                    item["classification_id"] = classID
                }

                // 概念ノードには固有の年度はない。年度はリンク論文側が持つ。
                return item
            }

            let nodeClassByID = Dictionary(uniqueKeysWithValues: ((out["nodes"] as? [[String: Any]]) ?? []).compactMap { node -> (String, String)? in
                guard let id = node["node_id"] as? String,
                      let classID = node["classification_id"] as? String else { return nil }
                return (id, classID)
            })

            out["papers"] = papers.map { paper in
                var item = paper
                let linkedNodeIDs = (item["syllabus_node_ids"] as? [String]) ?? []
                let linkedClasses = linkedNodeIDs.compactMap { nodeClassByID[$0] }
                if let classID = linkedClasses.first ?? _classificationID(from: item) {
                    item["classification_id"] = classID
                }

                var years = Set(_years(in: item.map { "\($0.key) \($0.value)" }.joined(separator: " ")))
                if years.isEmpty, let year = _firstYear(in: item) {
                    years.insert(year)
                }
                item["source_years"] = Array(years).sorted()
                item["source_year"] = years.max()
                return item
            }

            out["classification_schema_id"] = "inf6.science-classification.root-neighborhood.v1"
            out["source_family"] = manifest?.sourceFamily
            return out
        }

        private func _rootClassificationByNodeID(_ nodes: [[String: Any]]) -> [String: String] {
            let byID = Dictionary(uniqueKeysWithValues: nodes.compactMap { node -> (String, [String: Any])? in
                guard let id = node["node_id"] as? String else { return nil }
                return (id, node)
            })
            var out: [String: String] = [:]
            for node in nodes {
                guard let id = node["node_id"] as? String else { continue }
                var current = node
                var guardCount = 0
                var nearestScienceID = _scienceClassificationID(_classificationText(from: current))
                while let parentID = current["parent_node_id"] as? String,
                      let parent = byID[parentID],
                      guardCount < 32 {
                    current = parent
                    if let scienceID = _scienceClassificationID(_classificationText(from: current)) {
                        nearestScienceID = scienceID
                    }
                    guardCount += 1
                }
                if let classID = nearestScienceID ?? _classificationID(from: node) {
                    out[id] = classID
                }
            }
            return out
        }

        private func _classificationText(from item: [String: Any]) -> String {
            [
                item["classification_id"],
                item["title_ja"],
                item["title_en"],
                item["paper_title"],
                item["node_id"],
                item["paper_id"]
            ]
                .compactMap { $0 as? String }
                .joined(separator: " ")
        }

        private func _classificationID(from item: [String: Any]) -> String? {
            let candidates = [
                item["classification_id"],
                item["title_ja"],
                item["title_en"],
                item["paper_title"],
                item["node_id"],
                item["paper_id"]
            ]
            let rawCandidate = candidates
                .compactMap { $0 as? String }
                .first(where: { !$0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty })
            guard let raw = rawCandidate else {
                return nil
            }
            if let scienceID = _scienceClassificationID(raw) {
                return scienceID
            }
            let normalized = raw
                .lowercased()
                .replacingOccurrences(of: #"[^a-z0-9ぁ-んァ-ン一-龥]+"#, with: "-", options: .regularExpression)
                .trimmingCharacters(in: CharacterSet(charactersIn: "-"))
            return normalized.isEmpty ? nil : normalized
        }

