        private func _explicitYears(
            manifest: Inf6LearningFamilyManifest?,
            sourceSnapshot: [String: Any]?
        ) -> [Int] {
            var years = Set<Int>()

            if let sources = sourceSnapshot?["sources"] as? [[String: Any]] {
                for source in sources {
                    if let sourceYears = source["source_years"] as? [Int] {
                        years.formUnion(sourceYears)
                    }
                }
            }

            if let manifest {
                years.formUnion(_years(in: manifest.officialSources.joined(separator: " ")))
                years.formUnion(_years(in: manifest.trendSources.joined(separator: " ")))
                years.formUnion(_years(in: manifest.currentSources?.map(\.urlString).joined(separator: " ") ?? ""))

                if let examName = _examName(for: manifest),
                   let info = Inf6SyllabusUpdateChecker.shared.examScheduleInfo(for: examName) {
                    years.formUnion(_years(in: [
                        info.applicableSyllabusVersion,
                        info.applicableSyllabusId,
                        info.publishedSyllabusVersion,
                        info.publishedSyllabusId,
                        info.nextExamId,
                        info.nextExamStartDate,
                        info.nextExamEndDate
                    ].joined(separator: " ")))
                }

                years.formUnion(_bundledJDLALatestYears(familyID: manifest.familyID))
            }

            return years.filter { (1990...2100).contains($0) }.sorted()
        }

        private func _examName(for manifest: Inf6LearningFamilyManifest) -> String? {
            switch manifest.familyID {
            case "e-shikaku":
                return "E資格"
            case "g-kentei":
                return "G検定"
            case "ai-102":
                return "AI-102"
            case "ai-103":
                return "AI-103"
            default:
                return nil
            }
        }

        private func _bundledJDLALatestYears(familyID: String) -> [Int] {
            guard ["e-shikaku", "g-kentei"].contains(familyID) else { return [] }
            let sf = familyID == "e-shikaku" ? "jdla_eshikaku" : "jdla_gkentei"
            guard let url = Bundle.main.url(forResource: "schools_jdla.default", withExtension: "yaml") else {
                return []
            }
            guard let text = try? String(contentsOf: url, encoding: .utf8) else {
                return []
            }
            let marker = "key: \(familyID)"
            guard let start = text.range(of: marker) else { return [] }
            let rest = String(text[start.lowerBound...])
            let nextDepartment = rest.range(of: "\n          - key: ", options: [], range: rest.index(after: rest.startIndex)..<rest.endIndex)
            let block = nextDepartment.map { String(rest[..<$0.lowerBound]) } ?? rest
            return _years(in: block)
        }

        private func _years(in text: String) -> [Int] {
            guard let regex = try? NSRegularExpression(pattern: #"(?:19|20)\d{2}"#) else { return [] }
            let range = NSRange(text.startIndex..<text.endIndex, in: text)
            return regex.matches(in: text, range: range).compactMap { match in
                guard let range = Range(match.range, in: text),
                      let year = Int(text[range]) else { return nil }
                return year
            }
        }
