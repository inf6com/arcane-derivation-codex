        private func _parseStructuredGkenteiSyllabus(
            data: Data,
            url: URL
        ) throws -> [_StructuredGkenteiSyllabusRow] {
            guard let text = String(data: data, encoding: .utf8) else {
                throw NSError(
                    domain: "Inf6CircuitBoardView",
                    code: 23,
                    userInfo: [NSLocalizedDescriptionKey: "G検定 syllabus.yaml is not UTF-8: \(url.path)"]
                )
            }

            var rows: [_StructuredGkenteiSyllabusRow] = []
            var current: [String: String] = [:]

            func finishCurrent() throws {
                guard !current.isEmpty else { return }
                guard let key = current["key"], !key.isEmpty else {
                    throw NSError(
                        domain: "Inf6CircuitBoardView",
                        code: 24,
                        userInfo: [NSLocalizedDescriptionKey: "G検定 syllabus.yaml item key is missing: \(url.path)"]
                    )
                }
                guard let title = current["title"], !title.isEmpty else {
                    throw NSError(
                        domain: "Inf6CircuitBoardView",
                        code: 25,
                        userInfo: [NSLocalizedDescriptionKey: "G検定 syllabus.yaml title is missing: \(key)"]
                    )
                }
                guard let titleEn = current["title_en"], !titleEn.isEmpty else {
                    throw NSError(
                        domain: "Inf6CircuitBoardView",
                        code: 26,
                        userInfo: [NSLocalizedDescriptionKey: "seeded title_en is missing: \(key)"]
                    )
                }
                guard let depthText = current["depth"], let depth = Int(depthText) else {
                    throw NSError(
                        domain: "Inf6CircuitBoardView",
                        code: 27,
                        userInfo: [NSLocalizedDescriptionKey: "G検定 syllabus.yaml depth is invalid: \(key)"]
                    )
                }
                rows.append(_StructuredGkenteiSyllabusRow(
                    key: key,
                    title: title,
                    titleEn: titleEn,
                    summary: current["summary"],
                    summaryEn: current["summary_en"],
                    depth: depth
                ))
            }

            for rawLine in text.replacingOccurrences(of: "\r", with: "\n").split(separator: "\n", omittingEmptySubsequences: false) {
                let line = String(rawLine)
                let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
                guard !trimmed.isEmpty, !trimmed.hasPrefix("#"), trimmed != "outline:" else { continue }

                if trimmed.hasPrefix("- key:") {
                    try finishCurrent()
                    current.removeAll(keepingCapacity: true)
                    current["key"] = _yamlScalar(String(trimmed.dropFirst("- key:".count)))
                    continue
                }

                guard !current.isEmpty, let colon = trimmed.firstIndex(of: ":") else { continue }
                let field = String(trimmed[..<colon]).trimmingCharacters(in: .whitespacesAndNewlines)
                let valueStart = trimmed.index(after: colon)
                let value = _yamlScalar(String(trimmed[valueStart...]))
                if ["title", "title_en", "summary", "summary_en", "depth"].contains(field) {
                    current[field] = value
                }
            }
            try finishCurrent()
            return rows
        }

        private func _yamlScalar(_ raw: String) -> String {
            var value = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            if value.count >= 2,
               let first = value.first,
               let last = value.last,
               (first == "\"" && last == "\"") || (first == "'" && last == "'") {
                value.removeFirst()
                value.removeLast()
            }
            return value
        }

        private func _findMicrosoftLearnOutlineItems(
            for manifest: Inf6LearningFamilyManifest,
            cache: [String: [Inf6SyllabusOutlineItem]]
        ) -> [Inf6SyllabusOutlineItem] {
            let sourceURLs = Set((manifest.currentSources ?? []).map {
                $0.urlString.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
            }.filter { !$0.isEmpty })
            guard !sourceURLs.isEmpty else { return [] }

            var candidates: [[Inf6SyllabusOutlineItem]] = []
            for (key, items) in cache {
                let lowKey = key.lowercased()
                guard lowKey.hasSuffix("|microsoft_learn_outline_bilingual_v1") else { continue }
                if sourceURLs.contains(where: { lowKey.contains($0) }) {
                    candidates.append(items)
                }
            }
            return candidates.max(by: { $0.count < $1.count }) ?? []
        }

